// Fixture de integração isolada. Usa dependências já instaladas, sem npm install.
// PRISMO_DOCUMENT_TEST_PACKAGE=/ambiente/package.json node tests/document/build-portal.mjs
import {mkdtemp, mkdir, readFile, writeFile, cp, symlink, readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {spawn} from 'node:child_process';
import {fixture, color, token} from '../storybook/fixture.mjs';
const require=createRequire(process.env.PRISMO_DOCUMENT_TEST_PACKAGE || import.meta.url);
const core=dirname(require.resolve('@docusaurus/core/package.json'));
const packageFile=require.resolve('react/package.json');
const modules=dirname(dirname(packageFile));
const repo=fileURLToPath(new URL('../../',import.meta.url));
const root=await mkdtemp(join(tmpdir(),'prismo-document-visual-'));
await mkdir(join(root,'src/prismo'),{recursive:true});
await mkdir(join(root,'src/data'),{recursive:true});
await mkdir(join(root,'docs/foundations'),{recursive:true});
await cp(join(repo,'skills/prismo/assets/document'),join(root,'src/prismo/document'),{recursive:true});
await mkdir(join(root,'src/prismo/storybook'));
for(const name of ['catalog.mjs','dtcg.mjs','catalog.config.mjs']) await cp(join(repo,'skills/prismo/assets/storybook',name),join(root,'src/prismo/storybook',name));
await mkdir(join(root,'node_modules'));
await Promise.all((await readdir(modules)).filter(name=>name!=='.cache').map(name=>symlink(join(modules,name),join(root,'node_modules',name))));
await writeFile(join(root,'package.json'),JSON.stringify({name:'prismo-document-fixture',private:true,dependencies:{'@docusaurus/core':'3.10.2','@docusaurus/preset-classic':'3.10.2',react:'19.0.0','react-dom':'19.0.0'}}));
await writeFile(join(root,'docusaurus.config.mjs'),`export default {
 title:'Prismo · Documentação',url:'https://example.test',baseUrl:'/',onBrokenLinks:'throw',onBrokenAnchors:'throw',
 markdown:{hooks:{onBrokenMarkdownLinks:'throw',onBrokenMarkdownImages:'throw'}},
 i18n:{defaultLocale:'pt-BR',locales:['pt-BR']},
 presets:[['classic',{docs:{routeBasePath:'/',sidebarPath:'./sidebars.mjs'},blog:false,theme:{}}]],
 themeConfig:{navbar:{title:'Prismo · Fixture de templates'},colorMode:{defaultMode:'light',respectPrefersColorScheme:false}}
};`);
await writeFile(join(root,'sidebars.mjs'),`export default {docs:[{type:'autogenerated',dirName:'.'}]};`);
const tokens=fixture();
tokens.primitive.brand.blue=token('color',color([.15,.3,.75]));
tokens.semantic.light.primary.$value='{primitive.brand.blue}';
tokens.semantic.dark.primary.$value={colorSpace:'srgb',components:[.6,.75,1],alpha:1};
tokens.semantic.dark.background.$value={colorSpace:'srgb',components:[.055,.065,.085],alpha:1};
tokens.semantic.dark.surface.$value={colorSpace:'srgb',components:[.14,.16,.2],alpha:1};
tokens.semantic.dark.border.$value={colorSpace:'srgb',components:[.35,.4,.48],alpha:1};
tokens.semantic.light.border.$value={colorSpace:'srgb',components:[.6,.65,.7],alpha:1};
await writeFile(join(root,'src/data/tokens.json'),JSON.stringify(tokens));
const template=async name=>(await readFile(join(repo,'skills/prismo/assets/document',name+'.mdx'),'utf8'))
 .replace("from './DocumentUI'","from '@site/src/prismo/document/DocumentUI'");
for(const section of ['colors','typography','spacing','borders','elevation']) {
 let body=await template('Foundation');
 body=body.replace('Fundação — título a definir',section[0].toUpperCase()+section.slice(1))
 .replace('export const source = null;',"import source from '@site/src/data/tokens.json';")
 .replace('export const mapping = null;',"import mapping from '@site/src/prismo/storybook/catalog.config.mjs';")
 .replace('export const foundation = undefined;',`export const foundation = '${section}';`)
 .replace('export const semanticPaths = [];',`export const semanticPaths = ${JSON.stringify(section==='colors'?['semantic.light.primary','semantic.dark.primary']:section==='spacing'?['semantic.spacing.gap.default']:section==='typography'?['semantic.typography.body']:section==='borders'?['semantic.borders.radius.square','semantic.borders.radius.pill']:['semantic.elevation.dark.low'])};`)
 .replace('Descreva a finalidade desta fundação a partir das decisões aprovadas e os problemas de uso que ela resolve.','Fixture de teste dos templates: demonstrações derivadas de tokens sintéticos, sem representar decisões de um Design System consumidor.');
 await writeFile(join(root,'docs/foundations',section+'.mdx'),body);
}
await writeFile(join(root,'docs/index.md'),`---
title: Templates de documentação
slug: /
---

Fixture isolada, com tokens sintéticos.

- [Colors](./foundations/colors.mdx)
- [Typography](./foundations/typography.mdx)
- [Spacing](./foundations/spacing.mdx)
- [Borders](./foundations/borders.mdx)
- [Elevation](./foundations/elevation.mdx)
- [Componentes](./component.mdx)
- [Identidade](./identity.mdx)
`);
await writeFile(join(root,'docs/component.mdx'),(await template('Component')).replace('Componente — título a definir','Componente · estrutura documental'));
await writeFile(join(root,'docs/identity.mdx'),(await template('Identity')).replace('Identidade visual — título a definir','Identidade · estrutura documental'));
console.log('PORTAL_FIXTURE='+root);
const child=spawn(process.execPath,[join(core,'bin/docusaurus.mjs'),'build',root],{cwd:root,stdio:'inherit',env:{...process.env,DOCUSAURUS_TELEMETRY_DISABLED:'true',NO_UPDATE_NOTIFIER:'true',CI:'true'}});
child.on('exit',code=>{process.exitCode=code??1;});
